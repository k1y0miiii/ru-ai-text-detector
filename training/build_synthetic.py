#!/usr/bin/env python3
"""
build_synthetic.py — собирает синтетический «документ» для проверки document_scan.py.

Это SMOKE-TEST конвейера (отсев служебного -> окна -> проекция на абзацы), а НЕ
проверка точности детектора (она уже измерена: ROC-AUC 0.877). Поэтому регионы
берём из текстов, которые детектор классифицирует ОДНОЗНАЧНО — чтобы было видно,
правильно ли конвейер их ЛОКАЛИЗУЕТ.

Почему не только из samples/: окно детектора — 300 слов, а каждый наш sample ~45.
Регион из 3 сэмплов (~135 слов) короче окна -> окно заезжает в соседний класс и
размывает сигнал; а если удлинять регион ПОВТОРОМ сэмплов, повтор сам по себе
снижает burstiness/дисперсию перплексии и читается как ИИ — артефакт, который
ложно поднимает human-сторону. Поэтому «массу» региона берём из РАЗНЫХ длинных
размеченных абзацев нашего же data/test.jsonl (~300 слов каждый, без повторов),
а наши samples/ используем как (1) короткие «ловушки» <200 симв и (2) пару
содержательных абзацев внутри своих регионов.

Раскладка по классам (для последующей сверки):
  AI-регион:    2 длинных AI-абзаца (p~1.0) + sample_ai_1        -> «подозрительно»
  human-регион: 2 длинных human-абзаца (p~0.05) + sample_human_1 -> «человек»
  короткие вставки <200 симв (из samples/)                       -> «недостаточно текста»
  заголовки (Введение/глава/Заключение)                          -> «недостаточно текста»
  титул/оглавление/список литературы/приложение                 -> отсев (служебное)
"""

import json
import re
from pathlib import Path

S = Path("samples")


def r(name: str) -> str:
    return (S / name).read_text(encoding="utf-8").strip()


def _flat(text: str) -> str:
    """Схлопываем внутренние переносы — чтобы абзац остался ОДНИМ абзацем."""
    return re.sub(r"\s+", " ", text).strip()


# --- длинные РАЗНЫЕ размеченные абзацы из нашего же тест-сета ---------------
rows = [json.loads(l) for l in open("data/test.jsonl", encoding="utf-8")]
wc = lambda t: len(t.split())
ai_long = sorted((x for x in rows if x["label"] == 1), key=lambda x: -wc(x["text"]))
hum_long = sorted((x for x in rows if x["label"] == 0), key=lambda x: -wc(x["text"]))
# берём однозначно классифицируемые экземпляры (см. подбор в отчёте)
AI1, AI2 = _flat(ai_long[1]["text"]), _flat(ai_long[3]["text"])      # p~1.0
HUM1, HUM2 = _flat(hum_long[1]["text"]), _flat(hum_long[4]["text"])  # p~0.05

# --- наши samples/: короткие ловушки + по одному содержательному абзацу -----
short_human = "Здесь автор вставил короткую личную ремарку."          # ~44 симв
short_ai = "Таким образом, рассмотрев вопрос, перейдём к выводам."     # ~52 симв
samp_ai = r("sample_ai_1.txt")        # наш AI-сэмпл (в AI-регион)
samp_hum = r("sample_human_1.txt")    # наш human-сэмпл (в human-регион)

# человеческое заключение (>=200 симв, в надёжной зоне) -> метка «человек»
conclusion = (
    "В общем, пока возился со всем этим, понял простую вещь: проще сразу делать "
    "по-нормальному, чем потом переделывать. Половину времени убил на ерунду, "
    "которую можно было обойти, если бы не торопился. Зато теперь хоть знаю, как "
    "надо, и в следующий раз точно не полезу наобум — обидно за потраченные выходные."
)

doc = "\n\n".join([
    # --- титульник (служебное, до первого заголовка) ---
    "Министерство образования и науки Российской Федерации",
    "Федеральный университет, кафедра прикладной информатики",
    "КУРСОВАЯ РАБОТА\nна тему: «Применение методов анализа текста»",
    "Выполнил: студент группы ПИ-301\nПроверил: доц. Иванов И.И.",
    "Москва — 2024",
    # --- оглавление (служебное) ---
    "Содержание",
    "Введение .......................... 3\n"
    "1. Теоретическая часть ............ 5\n"
    "2. Практическая часть ............. 12\n"
    "Заключение ........................ 20\n"
    "Список литературы ................. 22",
    # --- содержательная часть: AI-регион ---
    "Введение",
    AI1,                # длинный AI (p~1.0)
    "1. Теоретическая часть",
    AI2,                # длинный AI (p~1.0)
    samp_ai,            # наш sample_ai_1 внутри AI-региона
    short_ai,           # короткий -> «недостаточно текста»
    # --- содержательная часть: human-регион ---
    "2. Практическая часть",
    HUM1,               # длинный human (p~0.05)
    HUM2,               # длинный human (p~0.05)
    samp_hum,           # наш sample_human_1 внутри human-региона
    short_human,        # короткий -> «недостаточно текста»
    "Заключение",
    conclusion,
    # --- back-matter (служебное, отсюда до конца — выбросить) ---
    "Список литературы",
    "1. Петров П.П. Анализ текстов. — М.: Наука, 2020. — 240 с.",
    "2. Сидоров С.С. Машинное обучение. — СПб.: Питер, 2021. — 320 с.",
    "Приложение А",
    "Таблица с исходными данными эксперимента приведена ниже.",
]) + "\n"

out = S / "synthetic_doc.txt"
out.write_text(doc, encoding="utf-8")
print(f"написал {out} ({len(doc)} симв, {doc.count(chr(10)+chr(10))+1} абзацев)")
